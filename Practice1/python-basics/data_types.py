# data_types.py

# Integer (int) — целые числа
a = 10
b = -5
print(a, type(a))
print(b, type(b))

# Float (float) — дробные числа
x = 3.14
y = -0.5
print(x, type(x))
print(y, type(y))

# String (str) — строки
name = "Aida"
text = 'Python is fun'
print(name, type(name))
print(text, type(text))

# Boolean (bool) — логические значения
is_python_easy = True
is_java_easy = False
print(is_python_easy, type(is_python_easy))
print(is_java_easy, type(is_java_easy))

# List (list) — изменяемая коллекция
numbers = [1, 2, 3, 4]
print(numbers, type(numbers))

# Tuple (tuple) — неизменяемая коллекция
point = (3, 5)
print(point, type(point))

# Set (set) — уникальные элементы
unique_numbers = {1, 2, 3, 3, 2}
print(unique_numbers, type(unique_numbers))

# Dictionary (dict) — ключ:значение
student = {
    "name": "Aida",
    "age": 18,
    "grade": "A"
}
print(student, type(student))
