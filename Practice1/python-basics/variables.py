# variables.py

# Числовые переменные
age = 18
year = 2026
price = 99.99

print(age)
print(year)
print(price)

# Строковые переменные
name = "Aida"
country = "Kazakhstan"

print(name)
print(country)

# Boolean переменные
is_student = True
is_working = False

print(is_student)
print(is_working)

# Перезапись переменной
age = 19
print("New age:", age)

# Использование переменных в выражениях
a = 10
b = 3
sum_ab = a + b
diff_ab = a - b

print("Sum:", sum_ab)
print("Difference:", diff_ab)

# Объединение строк
greeting = "Hello"
message = greeting + ", " + name
print(message)

# Ввод данных
city = input("Enter your city: ")
print("You live in", city)
